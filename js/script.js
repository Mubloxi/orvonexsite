async function loadSkinIntoViewer(viewer, sources, status, loader) {
    for (const source of sources) {
        try {
            await Promise.resolve(viewer.loadSkin(source, { ears: false, model: "auto-detect" }));
            scheduleSkinViewerCleanup(viewer);
            if (loader && loader.isConnected) {
                loader.remove();
            }
            clearSkinStatus(status);
            return true;
        } catch (error) {
            console.warn("Skin source failed:", source, error);
        }
    }

    if (loader) {
        loader.textContent = "Skin unavailable";
    }
    showSkinError(status, "Skin texture could not load");
    return false;
}

function createSkinViewer(frame, user, status, loader) {
    const canvas = document.createElement("canvas");
    canvas.className = "skin-canvas";
    canvas.setAttribute("aria-label", `${user.inGameName} Minecraft skin`);
    frame.appendChild(canvas);

    if (!window.skinview3d || !window.skinview3d.SkinViewer) {
        if (loader) {
            loader.textContent = "Skin viewer failed to load";
        }
        showSkinError(status, "Skin viewer is offline");
        return null;
    }

    const viewer = new skinview3d.SkinViewer({
        canvas,
        width: 260,
        height: 340,
        fov: 42,
        zoom: 0.88,
        enableControls: true
    });

    viewer.background = null;
    viewer.autoRotate = true;
    viewer.autoRotateSpeed = 0.9;
    viewer.controls.enablePan = false;
    viewer.controls.enableZoom = false;
    viewer.globalLight.intensity = 2.4;
    viewer.cameraLight.intensity = 0.8;
    viewer.animation = new skinview3d.IdleAnimation();
    viewer.animation.speed = 0.7;
    scheduleSkinViewerCleanup(viewer);

    resizeSkinViewer(viewer, frame);

    if (window.ResizeObserver) {
        const observer = new ResizeObserver(() => resizeSkinViewer(viewer, frame));
        observer.observe(frame);
        viewer._orvonexResizeObserver = observer;
    }

    activeSkinViewers.push(viewer);
    loadSkinIntoViewer(viewer, getSkinTextureSources(user), status, loader);

    return viewer;
}

