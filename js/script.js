function loadSkinTexture(user, model, loader, status) {
    const sources = getSkinTextureSources(user);
    const preview = new Image();
    let sourceIndex = 0;

    const trySource = () => {
        const source = sources[sourceIndex];
        model.style.setProperty("--skin-url", `url("${source}")`);
        preview.src = source;
    };

    preview.addEventListener("load", () => {
        if (loader && loader.isConnected) {
            loader.remove();
        }
        clearSkinStatus(status);
        model.classList.remove("texture-error");
    });

    preview.addEventListener("error", () => {
        sourceIndex += 1;

        if (sourceIndex < sources.length) {
            trySource();
            return;
        }

        if (loader) {
            loader.textContent = "Skin unavailable";
        }
        showSkinError(status, "Skin texture could not load");
        model.classList.add("texture-error");
    });

    trySource();
}

function setupSkinControls(userDiv, model, status) {
    const viewAngles = {
        front: "0deg",
        right: "-90deg",
        back: "180deg",
        left: "90deg"
    };
    const viewButtons = userDiv.querySelectorAll("[data-skin-view]");
    const rotateButton = userDiv.querySelector("[data-toggle-rotate]");

    const setRotating = isRotating => {
        model.classList.toggle("is-rotating", isRotating);

        if (rotateButton) {
            rotateButton.classList.toggle("active", isRotating);
            rotateButton.innerHTML = isRotating
                ? '<i class="fa-solid fa-pause"></i><span>Pause</span>'
                : '<i class="fa-solid fa-rotate"></i><span>Rotate</span>';
        }
    };

    viewButtons.forEach(button => {
        button.addEventListener("click", () => {
            const view = button.dataset.skinView;
            model.style.setProperty("--turn", viewAngles[view] || "0deg");
            setRotating(false);

            viewButtons.forEach(item => item.classList.remove("active"));
            button.classList.add("active");
            clearSkinStatus(status);
        });
    });

    if (rotateButton) {
        rotateButton.addEventListener("click", () => {
            const shouldRotate = !model.classList.contains("is-rotating");
            setRotating(shouldRotate);

            viewButtons.forEach(item => item.classList.remove("active"));
            clearSkinStatus(status);
        });
    }
}

function clearSkinStatus(status) {
    if (!status) return;
    status.textContent = "";
    status.classList.remove("error");
}

function showSkinError(status, message) {
    if (!status) return;
    status.textContent = message;
    status.classList.add("error");
}

function hideObjectTree(object) {
    if (!object || typeof object !== "object") return;

    if ("visible" in object) {
        object.visible = false;
    }

    if (typeof object.traverse === "function") {
        object.traverse(child => {
            if (child && typeof child === "object" && "visible" in child) {
                child.visible = false;
            }
        });
    }
}

function isSkinViewerExtra(object) {
    if (!object || typeof object !== "object") return false;

    const label = [
        object.name,
        object.type,
        object.constructor && object.constructor.name
    ].filter(Boolean).join(" ").replace(/[\s_-]+/g, "").toLowerCase();

    return label.includes("deadmau5")
        || label.includes("leftear")
        || label.includes("rightear")
        || label.includes("nametag")
        || label.includes("earmesh")
        || label === "ear"
        || label === "ears"
        || label.endsWith("ear")
        || label.endsWith("ears");
}

function hideSkinViewerExtras(viewer) {
    if (!viewer) return;

    ["nameTag", "nametag", "nameTagText"].forEach(prop => {
        if (typeof viewer[prop] === "string") {
            viewer[prop] = "";
        }
    });

    [
        viewer.nameTag,
        viewer.nametag,
        viewer.nameTagObject,
        viewer.playerObject && viewer.playerObject.nameTag,
        viewer.playerObject && viewer.playerObject.nametag,
        viewer.playerObject && viewer.playerObject.ears,
        viewer.playerObject && viewer.playerObject.leftEar,
        viewer.playerObject && viewer.playerObject.rightEar,
        viewer.playerObject && viewer.playerObject.skin && viewer.playerObject.skin.ears,
        viewer.playerObject && viewer.playerObject.skin && viewer.playerObject.skin.leftEar,
        viewer.playerObject && viewer.playerObject.skin && viewer.playerObject.skin.rightEar,
        viewer.playerWrapper && viewer.playerWrapper.nameTag,
        viewer.playerWrapper && viewer.playerWrapper.nametag
    ].forEach(hideObjectTree);

    [viewer.scene, viewer.playerObject, viewer.playerWrapper].forEach(root => {
        if (!root || typeof root.traverse !== "function") return;

        root.traverse(child => {
            if (isSkinViewerExtra(child)) {
                hideObjectTree(child);
            }
        });
    });
}

function scheduleSkinViewerCleanup(viewer) {
    hideSkinViewerExtras(viewer);

    if (typeof requestAnimationFrame === "function") {
        requestAnimationFrame(() => hideSkinViewerExtras(viewer));
    }

    window.setTimeout(() => hideSkinViewerExtras(viewer), 150);
}

function resizeSkinViewer(viewer, frame) {
    const width = Math.min(300, Math.max(230, frame.clientWidth || 260));
    viewer.width = width;
    viewer.height = 340;
}

