function renderAdminTeam() {
    const atContent = document.querySelector(".at-content");
    if (!atContent) return;

    const staffCount = document.getElementById("staff-count");
    const communityCountTitle = document.getElementById("community-count-title");
    const status = document.getElementById("skin-load-status");
    const entries = Object.entries(config.adminTeamPage);
    const totalMembers = entries.reduce((count, [, users]) => count + users.length, 0);

    activeSkinViewers.splice(0).forEach(viewer => {
        try {
            if (viewer._orvonexResizeObserver) {
                viewer._orvonexResizeObserver.disconnect();
            }
            viewer.dispose();
        } catch (error) {
            console.warn("Skin viewer cleanup failed", error);
        }
    });

    atContent.innerHTML = "";

    if (communityCountTitle) {
        communityCountTitle.textContent = `Community ${totalMembers} Members`;
    }

    if (staffCount) {
        staffCount.textContent = `${totalMembers} community ${totalMembers === 1 ? "member" : "members"}`;
    }

    if (status) {
        status.textContent = "";
    }

    entries.forEach(([team, users]) => {
        const group = document.createElement("section");
        group.className = `group ${team}`;

        group.innerHTML = `
            <div class="group-heading">
                <h2 class="group-title">${escapeHtml(formatGroupName(team))}</h2>
                <span>${users.length} ${users.length === 1 ? "member" : "members"}</span>
            </div>
            <div class="users"></div>
        `;

        const usersContainer = group.querySelector(".users");

        users.forEach(user => {
            const groupColor = config.atGroupsDefaultColors[team] || "var(--default-rank-color)";
            const rankColor = user.rankColor || groupColor;
            usersContainer.appendChild(buildAdminCard(user, team, rankColor));
        });

        atContent.appendChild(group);
    });

    if (status) {
        status.textContent = "";
    }
}

