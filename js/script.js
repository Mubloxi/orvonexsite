function escapeHtml(value) {
    return String(value)
        .replace(/&/g, "&amp;")
        .replace(/</g, "&lt;")
        .replace(/>/g, "&gt;")
        .replace(/"/g, "&quot;")
        .replace(/'/g, "&#039;");
}

function formatGroupName(value) {
    return String(value)
        .replace(/([a-z0-9])([A-Z])/g, "$1 $2")
        .replace(/[-_]/g, " ")
        .replace(/\b\w/g, letter => letter.toUpperCase());
}

function withCacheBust(url) {
    if (!url || url.startsWith("data:")) return url;
    return `${url}${url.includes("?") ? "&" : "?"}refresh=${skinRefreshStamp}`;
}

function getSkinTextureSources(user) {
    const username = encodeURIComponent(user.inGameName);
    const customSkin = user.skinUrlOrPathToFile ? user.skinUrlOrPathToFile.trim() : "";
    const sources = [
        `https://minotar.net/skin/${username}`,
        `https://mc-heads.net/skin/${username}`
    ];

    if (customSkin) {
        sources.unshift(customSkin);
    }

    return sources.map(withCacheBust);
}

async function copyText(text) {
    if (navigator.clipboard && window.isSecureContext) {
        await navigator.clipboard.writeText(text);
        return;
    }

    const textarea = document.createElement("textarea");
    textarea.value = text;
    textarea.setAttribute("readonly", "");
    textarea.style.position = "fixed";
    textarea.style.left = "-9999px";
    document.body.appendChild(textarea);
    textarea.select();
    const copied = document.execCommand("copy");
    textarea.remove();

    if (!copied) {
        throw new Error("Copy command failed");
    }
}

function setupMobileMenu() {
    const hamburger = document.querySelector(".hamburger");
    const links = document.querySelector(".links");

    if (!hamburger || !links) return;

    hamburger.setAttribute("role", "button");
    hamburger.setAttribute("tabindex", "0");
    hamburger.setAttribute("aria-label", "Toggle navigation");
    hamburger.setAttribute("aria-expanded", "false");

    const toggleMenu = () => {
        const isActive = links.classList.toggle("active");
        hamburger.setAttribute("aria-expanded", String(isActive));
    };

    hamburger.addEventListener("click", toggleMenu);
    hamburger.addEventListener("keydown", event => {
        if (event.key === "Enter" || event.key === " ") {
            event.preventDefault();
            toggleMenu();
        }
    });

    links.querySelectorAll(".link").forEach(link => {
        link.addEventListener("click", () => {
            links.classList.remove("active");
            hamburger.setAttribute("aria-expanded", "false");
        });
    });
}

function setActiveNav() {
    const currentPage = window.location.pathname.split("/").pop() || "index.html";
    const currentHash = window.location.hash;
    const navLinks = document.querySelectorAll(".navbar .links .link");

    navLinks.forEach(link => {
        const href = link.getAttribute("href");
        const [hrefPage, hrefHashPart] = href.split("#");
        const hrefHash = hrefHashPart ? `#${hrefHashPart}` : "";
        const isCurrentPage = hrefPage === currentPage || (!hrefPage && currentPage === "index.html");
        const isPageOnlyLink = isCurrentPage && !hrefHash && !currentHash;
        const isSectionLink = isCurrentPage && hrefHash && currentHash === hrefHash;

        link.classList.toggle("active", isPageOnlyLink || isSectionLink);
    });
}

