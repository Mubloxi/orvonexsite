function setFaceTexture(face, uv) {
    const [u, v, width, height] = uv;

    face.style.width = `${width * SKIN_UNIT}px`;
    face.style.height = `${height * SKIN_UNIT}px`;
    face.style.backgroundSize = `${64 * SKIN_UNIT}px ${64 * SKIN_UNIT}px`;
    face.style.backgroundPosition = `-${u * SKIN_UNIT}px -${v * SKIN_UNIT}px`;
}

function setFaceTransform(face, direction, part, layerOffset = 0) {
    const px = SKIN_UNIT;
    const halfWidth = (part.w * px) / 2;
    const halfHeight = (part.h * px) / 2;
    const halfDepth = (part.d * px) / 2;
    const offset = layerOffset * px;

    switch (direction) {
        case "front":
            face.style.left = "0";
            face.style.top = "0";
            face.style.transform = `translateZ(${halfDepth + offset}px)`;
            break;
        case "back":
            face.style.left = "0";
            face.style.top = "0";
            face.style.transform = `rotateY(180deg) translateZ(${halfDepth + offset}px)`;
            break;
        case "left":
            face.style.left = `${((part.w - part.d) * px) / 2}px`;
            face.style.top = "0";
            face.style.transform = `rotateY(-90deg) translateZ(${halfWidth + offset}px)`;
            break;
        case "right":
            face.style.left = `${((part.w - part.d) * px) / 2}px`;
            face.style.top = "0";
            face.style.transform = `rotateY(90deg) translateZ(${halfWidth + offset}px)`;
            break;
        case "top":
            face.style.left = "0";
            face.style.top = `${((part.h - part.d) * px) / 2}px`;
            face.style.transform = `rotateX(90deg) translateZ(${halfHeight + offset}px)`;
            break;
        case "bottom":
            face.style.left = "0";
            face.style.top = `${((part.h - part.d) * px) / 2}px`;
            face.style.transform = `rotateX(-90deg) translateZ(${halfHeight + offset}px)`;
            break;
    }
}

function createFace(direction, uv, part, layerOffset) {
    const face = document.createElement("span");
    face.className = `mc-face ${direction}`;
    setFaceTexture(face, uv);
    setFaceTransform(face, direction, part, layerOffset);
    return face;
}

function createCuboid(part, textureSet, layerClass, layerOffset = 0) {
    const cuboid = document.createElement("div");
    cuboid.className = `mc-cuboid ${part.className} ${layerClass}`;
    cuboid.style.width = `${part.w * SKIN_UNIT}px`;
    cuboid.style.height = `${part.h * SKIN_UNIT}px`;
    cuboid.style.transform = `translate3d(${part.x * SKIN_UNIT}px, ${part.y * SKIN_UNIT}px, 0)`;

    Object.entries(textureSet).forEach(([direction, uv]) => {
        cuboid.appendChild(createFace(direction, uv, part, layerOffset));
    });

    return cuboid;
}

